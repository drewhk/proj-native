"""Regenerate somerc_latc.gie with Python + mpmath (not needed to run GIE).

These are mathematical reference values, not captures from an official converter.
Use 80-digit arithmetic and the closed-form Gaussian-sphere equations described
by Toth (2022), https://doi.org/10.30921/GK.74.2022.5.321, equations 1-3.
The spherical rotation is evaluated with atan2 and the Mercator northing with
atanh, independently of somerc.cpp's asin / log(tan()) evaluation.
Constants are derived from the ellipsoid, not copied from rounded A.1 tables.
"""

from pathlib import Path

import mpmath as mp

mp.mp.dps = 80
D = mp.mpf
rad = mp.pi / 180


def project(lon, lat, normal, centre, lon0, radius, rf, scale, east, north):
    phi = D(lat) * rad
    phi_n = D(normal) * rad
    phi_c = D(centre) * rad
    f = 1 / D(rf) if rf else D(0)
    e2 = f * (2 - f)
    e = mp.sqrt(e2)
    n = mp.sqrt(1 + e2 * mp.cos(phi_n) ** 4 / (1 - e2))
    beta_n = mp.asin(mp.sin(phi_n) / n)

    def isometric(p):
        return mp.asinh(mp.tan(p)) - e * mp.atanh(e * mp.sin(p))

    beta = mp.atan(mp.sinh(mp.asinh(mp.tan(beta_n))
                           + n * (isometric(phi) - isometric(phi_n))))
    delta = n * (D(lon) - D(lon0)) * rad
    # Rotate a unit vector on the Gaussian sphere about its east-west axis.
    x = mp.cos(phi_c) * mp.cos(beta) * mp.cos(delta) + mp.sin(phi_c) * mp.sin(beta)
    y = mp.cos(beta) * mp.sin(delta)
    z = mp.cos(phi_c) * mp.sin(beta) - mp.sin(phi_c) * mp.cos(beta) * mp.cos(delta)
    r = D(radius) * mp.sqrt(1 - e2) / (1 - e2 * mp.sin(phi_n) ** 2)
    return (D(east) + D(scale) * r * mp.atan2(y, x),
            D(north) + D(scale) * r * mp.atanh(z))


lines = ["<gie-strict>",
         "# Generated by somerc_reference.py using 80-digit mpmath arithmetic.",
         "# Mathematical checks only; not official EHT conformance fixtures.",
         "# 0.1 micrometre tolerance allows binary64 evaluation error."]


def case(name, definition, params, points):
    lines.extend(["", "# " + name, "operation " + definition, "tolerance 0.0001 mm"])
    for lon, lat in points:
        east, north = project(lon, lat, *params)
        # Preserve z/time as well as verifying both horizontal directions.
        source = f"{lon} {lat} 123.45 2026"
        target = f"{mp.nstr(east, 25)} {mp.nstr(north, 25)} 123.45 2026"
        lines.extend(["direction forward", "accept " + source,
                      "expect " + target, "roundtrip 1",
                      "direction inverse", "accept " + target,
                      "expect " + source, "roundtrip 1"])


case("EOV: independent normal parallel and spherical centre; centre and edges",
     "+proj=somerc +ellps=GRS67 +lat_0=47.1666666666667 +latc=47.1 "
     "+lon_0=19.04857177777778 +k_0=0.99993 +x_0=650000 +y_0=200000",
     ("47.1666666666667", "47.1", "19.04857177777778", "6378160",
      "298.2471674270", "0.99993", "650000", "200000"),
     [("16", "46"), ("16", "48"), ("23", "46"), ("23", "48"),
      ("19", "47"), ("20", "48.5"), ("18", "45.8"),
      ("19.04857177777778", "47.1666666666667")])

case("Southern ellipsoidal case with a DMS centre",
     "+proj=somerc +ellps=GRS67 +lat_0=-47.1666666666667 +latc=47d6'S "
     "+lon_0=19 +k_0=0.99993",
     ("-47.1666666666667", "-47.1", "19", "6378160",
      "298.2471674270", "0.99993", "0", "0"),
     [("16", "-46"), ("23", "-48"), ("19", "-47")])

for centre, points in [("0", [("0", "20"), ("5", "25")]),
                       ("30", [("0", "30"), ("5", "25")]),
                       ("90", [("0", "80"), ("5", "80")]),
                       ("-90", [("0", "-80"), ("5", "-80")])]:
    case("Sphere: explicit centre " + centre,
         f"+proj=somerc +R=6400000 +lat_0=20 +latc={centre}",
         ("20", centre, "0", "6400000", None, "1", "0", "0"), points)

# The omitted parameter and an explicitly equivalent spherical centre must
# both retain the ordinary Swiss result, including its nonzero normal parallel.
normal = D("46.95240555555556")
f = 1 / D("299.1528128")
e2 = f * (2 - f)
n = mp.sqrt(1 + e2 * mp.cos(normal * rad) ** 4 / (1 - e2))
centre = mp.nstr(mp.asin(mp.sin(normal * rad) / n) / rad, 40)
swiss = "+proj=somerc +ellps=bessel +lat_0=46.95240555555556 +lon_0=7.439583333333333 +x_0=600000 +y_0=200000"
for suffix in ["", " +latc=" + centre]:
    case("Ordinary Swiss mapping" + (" (explicit centre)" if suffix else " (default)"),
         swiss + suffix,
         (str(normal), centre, "7.439583333333333", "6377397.155",
          "299.1528128", "1", "600000", "200000"),
         [("6", "46"), ("8", "47"), ("10", "47.5")])

for invalid in ["91", "-91", "nan", "inf", "1e999", "", "+", "N", "47junk"]:
    lines.extend(["", "# Reject invalid centre", f"operation +proj=somerc +latc={invalid}",
                  "expect failure errno invalid_op_illegal_arg_value"])

lines.extend(["", "</gie-strict>", ""])
Path(__file__).with_name("somerc_latc.gie").write_text("\n".join(lines), encoding="utf-8")
